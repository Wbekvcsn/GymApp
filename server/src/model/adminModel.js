const mongoose=require('mongoose');
const adminSchema=new mongoose.Schema(
    {
        name:{
        type:String,
        required:true,
        trim:true
    },
    email:{
        type:String,
        required:true,
        unique:true,
        trim:true,
        lowercase:true
    },
    password:{
        type:String,
        required:true
    },
    phone:{
        type:String,
        required:true,
        trim:true
    },
    gymName:{
        type:String,
        required:true,
        trim:true
    },
    gymAddress:{
        type:String,
        required:true,
        trim:true
    },
    isactive:{
        type:Boolean,
        default:true
    }
},{timestamps:true}    
)
const adminModel=mongoose.model("Admin",adminSchema);
module.exports=adminModel;